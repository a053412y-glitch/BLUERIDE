/**
 * פונקציה להגרלת אטרקציה אקראית (גלגל המזל)
 * מופעלת בלחיצה על הכפתור בעמוד ההזמנות
 */
function chooseRandomActivity() {
    
    // 1. יצירת מערך (רשימה) של כל האטרקציות המטורפות שיש לנו באתר
    const activities = [
        "🍌 בננה אקסטרים מטורפת ומהירה!",
        "🚤 ספינת טורנדו מהירה בסילון מים!",
        "🌊 אופנוע ים סילון - כוח מטורף על הגלים!",
        "🛋️ ספת אבובים קבוצתית קורעת מצחוק!"
    ];
    
    // 2. הגרלת מספר אקראי שמתאים למיקומים ברשימה (מספר שלם בין 0 ל-3)
    // Math.random מייצר מספר עשרוני בין 0 ל-1, מכפילים אותו באורך הרשימה ומעגלים למטה עם Math.floor
    const randomIndex = Math.floor(Math.random() * activities.length);
    
    // 3. הצגת חלונית הודעה קופצת (alert) למשתמש עם האטרקציה שנבחרה עבורו
    alert("הכנרת החליטה בשבילכם! האטרקציה שלכם היא:\n\n" + activities[randomIndex]);
}